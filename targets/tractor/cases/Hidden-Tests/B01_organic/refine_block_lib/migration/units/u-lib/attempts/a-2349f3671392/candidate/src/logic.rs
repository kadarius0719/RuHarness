pub fn refine_block(block: &[u8], pmax16: &mut u16, pmin16: &mut u16, mask: u32) -> i32 {
    const W1_TAB: [i32; 4] = [3, 0, 2, 1];
    const PRODS: [i32; 4] = [0x090000, 0x000900, 0x040102, 0x010402];

    let old_min = *pmin16;
    let old_max = *pmax16;

    let mut max16: u16;
    let mut min16: u16;

    if (mask ^ (mask << 2)) < 4 {
        let mut r = 8i32;
        let mut g = 8i32;
        let mut b = 8i32;

        for i in 0..16 {
            r = r.wrapping_add(block[i * 4 + 0] as i32);
            g = g.wrapping_add(block[i * 4 + 1] as i32);
            b = b.wrapping_add(block[i * 4 + 2] as i32);
        }

        r >>= 4;
        g >>= 4;
        b >>= 4;

        max16 = ((STB_OMATCH5[r as usize][0] as u16) << 11)
            | ((STB_OMATCH6[g as usize][0] as u16) << 5)
            | (STB_OMATCH5[b as usize][0] as u16);
        min16 = ((STB_OMATCH5[r as usize][1] as u16) << 11)
            | ((STB_OMATCH6[g as usize][1] as u16) << 5)
            | (STB_OMATCH5[b as usize][1] as u16);
    } else {
        let mut at1_r = 0i32;
        let mut at1_g = 0i32;
        let mut at1_b = 0i32;
        let mut at2_r = 0i32;
        let mut at2_g = 0i32;
        let mut at2_b = 0i32;
        let mut cm = mask;
        let mut akku = 0i32;

        for i in 0..16 {
            let step = (cm & 3) as usize;
            let w1 = W1_TAB[step];
            let r = block[i * 4 + 0] as i32;
            let g = block[i * 4 + 1] as i32;
            let b = block[i * 4 + 2] as i32;

            akku = akku.wrapping_add(PRODS[step]);
            at1_r = at1_r.wrapping_add(w1.wrapping_mul(r));
            at1_g = at1_g.wrapping_add(w1.wrapping_mul(g));
            at1_b = at1_b.wrapping_add(w1.wrapping_mul(b));
            at2_r = at2_r.wrapping_add(r);
            at2_g = at2_g.wrapping_add(g);
            at2_b = at2_b.wrapping_add(b);

            cm >>= 2;
        }

        at2_r = 3i32.wrapping_mul(at2_r).wrapping_sub(at1_r);
        at2_g = 3i32.wrapping_mul(at2_g).wrapping_sub(at1_g);
        at2_b = 3i32.wrapping_mul(at2_b).wrapping_sub(at1_b);

        let xx = (akku >> 16) as i32;
        let yy = ((akku >> 8) & 0xff) as i32;
        let xy = (akku & 0xff) as i32;

        let f = 3.0f32 / 255.0f32 / ((xx as f32 * yy as f32) - (xy as f32 * xy as f32));

        max16 = quantize5((at1_r as f32 * yy as f32 - at2_r as f32 * xy as f32) * f) << 11;
        max16 |= quantize6((at1_g as f32 * yy as f32 - at2_g as f32 * xy as f32) * f) << 5;
        max16 |= quantize5((at1_b as f32 * yy as f32 - at2_b as f32 * xy as f32) * f);

        min16 = quantize5((at2_r as f32 * xx as f32 - at1_r as f32 * xy as f32) * f) << 11;
        min16 |= quantize6((at2_g as f32 * xx as f32 - at1_g as f32 * xy as f32) * f) << 5;
        min16 |= quantize5((at2_b as f32 * xx as f32 - at1_b as f32 * xy as f32) * f);
    }

    *pmin16 = min16;
    *pmax16 = max16;

    if old_min != min16 || old_max != max16 { 1 } else { 0 }
}
